/*
=============================================================================
EnadIA TECH — Supabase PostgreSQL Migration
=============================================================================

MULTI-TENANCY ARCHITECTURE
==========================
This schema supports a multi-tenancy model via an `instance` column on key
tables (users, student_responses, local_question_responses, essay_answers).

  • Each row belongs to exactly one "instance" (tenant), identified by a TEXT
    value such as 'ENADIA', 'UNIP', 'ESTACIO', etc.
  • The default instance is 'ENADIA', representing the original EnadIA platform.
  • Business logic in the application layer is responsible for filtering queries
    by the current user's instance — no Row Level Security (RLS) is used because
    the app implements its own custom JWT authentication (not Supabase Auth).
  • Composite unique constraints on (email, instance) and (ra, instance) allow
    the same email or RA to exist in different tenants without conflict.
  • Indexes on `instance` are added to all tenant-scoped tables for efficient
    filtering.

ID CONVENTION
==============
  • All primary keys use TEXT to store CUID strings generated by the
    application layer (e.g. `cuid()` from the `@paralleldrive/cuid2` library).
  • UUIDs are NOT used anywhere in this schema.

ENUM POLICY
============
  • PostgreSQL ENUM types are NOT used. All constrained string columns use
    TEXT with CHECK constraints for maximum flexibility and easier migrations.

AUTHENTICATION
==============
  • The application uses custom JWT-based authentication (bcrypt passwords,
    signed JWTs issued by the Next.js API). Supabase Auth is NOT used.
  • Consequently, no RLS policies, no auth.uid() references, and no
    anon/auth role grants are present in this schema.

=============================================================================
*/


