-- Auto-update `updated_at` timestamp on every row modification.
-- Attach this trigger to any table that has an `updated_at` column.
CREATE OR REPLACE FUNCTION public.trigger_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;


