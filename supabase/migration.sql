-- ---------------------------------------------------------------------------
-- 2.1  users
-- ---------------------------------------------------------------------------
-- Central identity table. The `instance` column enables the same email / RA
-- to exist in different tenants. Role is constrained via CHECK.

CREATE TABLE public.users (
  id            TEXT    PRIMARY KEY,                          -- CUID generated by app
  instance      TEXT    NOT NULL DEFAULT 'ENADIA',
  email         TEXT    NOT NULL,
  name          TEXT    NOT NULL,
  password      TEXT    NOT NULL,                             -- bcrypt hash
  role          TEXT    NOT NULL DEFAULT 'ALUNO'
                CHECK (role IN ('MASTER', 'PROFESSOR', 'ALUNO')),
  ra            TEXT,                                          -- academic registration
  avatar        TEXT,
  active        BOOLEAN NOT NULL DEFAULT true,
  last_login    TIMESTAMPTZ,

  -- Student-specific fields
  curso         TEXT,                                          -- course name
  periodo       INTEGER,                                       -- semester / period
  modalidade    TEXT    DEFAULT 'PRESENCIAL'
                CHECK (modalidade IN ('EAD', 'PRESENCIAL', 'SEMIPRESENCIAL')),

  -- Professor-specific fields
  disciplina    TEXT,                                          -- professor's subject

  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- Constraints
  CONSTRAINT uq_users_email_instance  UNIQUE (email, instance),
  CONSTRAINT uq_users_ra_instance    UNIQUE (ra, instance)
);

-- ---------------------------------------------------------------------------
-- 2.2  microareas
-- ---------------------------------------------------------------------------
-- Content categories / knowledge areas for the ENADE exam.

CREATE TABLE public.microareas (
  id            TEXT    PRIMARY KEY,                          -- CUID
  name          TEXT    NOT NULL UNIQUE,
  code          TEXT    NOT NULL UNIQUE,
  macroarea     TEXT    NOT NULL,                             -- parent macro-area name
  description   TEXT    NOT NULL,
  color         TEXT    NOT NULL DEFAULT '#3b82f6',
  "order"       INTEGER NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 2.3  elements
-- ---------------------------------------------------------------------------
-- Specific competency elements within a microarea.

CREATE TABLE public.elements (
  id            TEXT    PRIMARY KEY,                          -- CUID
  code          TEXT    NOT NULL UNIQUE,
  name          TEXT    NOT NULL,
  description   TEXT    NOT NULL,
  skill_level   TEXT    NOT NULL DEFAULT 'compreensão',
  microarea_id  TEXT    NOT NULL REFERENCES public.microareas(id) ON DELETE CASCADE,
  "order"       INTEGER NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 2.4  questions
-- ---------------------------------------------------------------------------
-- The question bank. Questions authored by professors go through a lifecycle
-- of draft → test → validation → active.

CREATE TABLE public.questions (
  id              TEXT    PRIMARY KEY,                        -- CUID
  code            TEXT    NOT NULL UNIQUE,
  type            TEXT    NOT NULL DEFAULT 'OBJETIVA'
                  CHECK (type IN ('OBJETIVA', 'DISSERTATIVA')),
  statement       TEXT    NOT NULL,
  context         TEXT,                                      -- optional context block
  correct_answer  TEXT    NOT NULL,
  explanation     TEXT,                                      -- post-answer explanation
  difficulty      TEXT    NOT NULL DEFAULT 'médio',

  -- TRI (Item Response Theory) parameters
  tri_a           FLOAT,
  tri_b           FLOAT,
  tri_c           FLOAT,
  tri_calibrated  BOOLEAN NOT NULL DEFAULT false,

  -- Provenance
  source          TEXT    NOT NULL DEFAULT 'elaborada',
  source_year     INTEGER,                                   -- e.g. 2023 ENADE
  enade_id        TEXT,                                      -- original ENADE question ID

  -- Relations
  microarea_id    TEXT    NOT NULL REFERENCES public.microareas(id),
  element_id      TEXT    REFERENCES public.elements(id),
  author_id       TEXT    REFERENCES public.users(id),
  validator_id    TEXT    REFERENCES public.users(id),

  status          TEXT    NOT NULL DEFAULT 'RASCUNHO'
                  CHECK (status IN (
                    'RASCUNHO',
                    'AGUARDANDO_TESTE',
                    'EM_TESTE',
                    'AGUARDANDO_VALIDACAO',
                    'APROVADA',
                    'REPROVADA',
                    'ATIVA',
                    'INATIVA'
                  )),

  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 2.5  alternatives
-- ---------------------------------------------------------------------------
-- Multiple-choice options for OBJETIVA questions.

CREATE TABLE public.alternatives (
  id            TEXT    PRIMARY KEY,                        -- CUID
  letter        TEXT    NOT NULL,                           -- A, B, C, D, E
  text          TEXT    NOT NULL,
  question_id   TEXT    NOT NULL REFERENCES public.questions(id) ON DELETE CASCADE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 2.6  simulados
-- ---------------------------------------------------------------------------
-- Exam simulations (practice tests). Different types serve different purposes.

CREATE TABLE public.simulados (
  id            TEXT    PRIMARY KEY,                        -- CUID
  title         TEXT    NOT NULL,
  description   TEXT,
  type          TEXT    NOT NULL DEFAULT 'LIVRE'
                CHECK (type IN (
                  'DIAGNOSTICO',
                  'MICROAREA',
                  'MACROAREA',
                  'GERAL',
                  'LIVRE',
                  'ENADE_SIMULADO'
                )),
  phase         INTEGER,                                   -- associated phase (1-4)
  time_limit    INTEGER,                                   -- seconds; NULL = no limit
  question_count INTEGER NOT NULL DEFAULT 10,
  active        BOOLEAN NOT NULL DEFAULT true,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 2.7  simulado_configs
-- ---------------------------------------------------------------------------
-- Junction table linking questions to simulados with ordering.

CREATE TABLE public.simulado_configs (
  id            TEXT    PRIMARY KEY,                        -- CUID
  simulado_id   TEXT    NOT NULL REFERENCES public.simulados(id) ON DELETE CASCADE,
  question_id   TEXT    NOT NULL REFERENCES public.questions(id),
  "order"       INTEGER NOT NULL DEFAULT 0
);

-- ---------------------------------------------------------------------------
-- 2.8  student_responses
-- ---------------------------------------------------------------------------
-- Records answers to database-stored questions (inside simulados or practice).
-- Scoped by `instance` for multi-tenant isolation.

CREATE TABLE public.student_responses (
  id            TEXT    PRIMARY KEY,                        -- CUID
  instance      TEXT    NOT NULL DEFAULT 'ENADIA',
  user_id       TEXT    NOT NULL REFERENCES public.users(id),
  question_id   TEXT    NOT NULL REFERENCES public.questions(id),
  simulado_id   TEXT    REFERENCES public.simulados(id),
  answer        TEXT    NOT NULL,
  is_correct    BOOLEAN,
  response_time INTEGER,                                   -- milliseconds
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 2.9  local_question_responses  ★ CRITICAL TABLE ★
-- ---------------------------------------------------------------------------
-- Tracks student responses to questions that exist ONLY in the client-side
-- in-memory question bank (enade-full-bank.ts). These questions do NOT have
-- a row in the `questions` table — their source data lives entirely on the
-- client and is baked into the build.
--
-- The `question_bank_id` field stores the ID as it appears in the in-memory
-- bank, allowing the app to correlate responses back to the correct question.
-- Topic and macroarea are denormalised here so analytics can be computed
-- without joining to any question table.

CREATE TABLE public.local_question_responses (
  id              TEXT    PRIMARY KEY,                      -- CUID
  instance        TEXT    NOT NULL DEFAULT 'ENADIA',
  user_id         TEXT    NOT NULL REFERENCES public.users(id),
  question_bank_id TEXT   NOT NULL,                         -- ID from in-memory bank
  topic           TEXT    NOT NULL,                         -- microarea name (denormalised)
  macroarea       TEXT    NOT NULL,                         -- macroarea name (denormalised)
  difficulty      TEXT,                                    -- question difficulty level
  answer          TEXT    NOT NULL,                         -- student's answer
  correct_answer  TEXT    NOT NULL,                         -- expected correct answer
  is_correct      BOOLEAN NOT NULL,
  response_time   INTEGER,                                 -- milliseconds
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 2.10 essay_answers
-- ---------------------------------------------------------------------------
-- Stores essay (dissertativa) submissions and AI-generated feedback.
-- Scoped by `instance` for multi-tenant isolation.

CREATE TABLE public.essay_answers (
