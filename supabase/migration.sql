-- ---------------------------------------------------------------------------
-- 5.1  student_ranking
-- ---------------------------------------------------------------------------
-- Aggregated ranking view combining responses from both database questions
-- (student_responses) and in-memory bank questions (local_question_responses).

CREATE OR REPLACE VIEW public.student_ranking AS
SELECT
  u.id            AS user_id,
  u.instance      AS instance,
  u.name,
  u.email,
  u.ra,
  u.curso,
  u.periodo,
  u.modalidade,

  -- DB question responses
  COUNT(sr.id)    AS db_total_answered,
  COUNT(sr.id) FILTER (WHERE sr.is_correct = true) AS db_total_correct,

  -- Local bank question responses
  COUNT(lqr.id)  AS local_total_answered,
  COUNT(lqr.id) FILTER (WHERE lqr.is_correct = true) AS local_total_correct,

  -- Combined totals
  (COALESCE(COUNT(sr.id), 0) + COALESCE(COUNT(lqr.id), 0)) AS total_answered,
  (COALESCE(COUNT(sr.id) FILTER (WHERE sr.is_correct = true), 0)
   + COALESCE(COUNT(lqr.id) FILTER (WHERE lqr.is_correct = true), 0)) AS total_correct,

  CASE
    WHEN (COALESCE(COUNT(sr.id), 0) + COALESCE(COUNT(lqr.id), 0)) > 0
    THEN ROUND(
      (COALESCE(COUNT(sr.id) FILTER (WHERE sr.is_correct = true), 0)
       + COALESCE(COUNT(lqr.id) FILTER (WHERE lqr.is_correct = true), 0))
      ::FLOAT
      / (COALESCE(COUNT(sr.id), 0) + COALESCE(COUNT(lqr.id), 0))::FLOAT
      * 100
    )
    ELSE 0
  END AS hit_rate,

  CASE
    WHEN AVG(sr.response_time) IS NOT NULL OR AVG(lqr.response_time) IS NOT NULL
    THEN ROUND(
      COALESCE(AVG(sr.response_time), 0)
      + COALESCE(AVG(lqr.response_time), 0)
    )
    ELSE NULL
  END AS avg_response_time,

  RANK() OVER (
    PARTITION BY u.instance
    ORDER BY
      CASE
        WHEN (COALESCE(COUNT(sr.id), 0) + COALESCE(COUNT(lqr.id), 0)) > 0
        THEN ROUND(
          (COALESCE(COUNT(sr.id) FILTER (WHERE sr.is_correct = true), 0)
           + COALESCE(COUNT(lqr.id) FILTER (WHERE lqr.is_correct = true), 0))
          ::FLOAT
          / (COALESCE(COUNT(sr.id), 0) + COALESCE(COUNT(lqr.id), 0))::FLOAT
          * 100
        )
        ELSE 0
      END DESC,
      (COALESCE(COUNT(sr.id) FILTER (WHERE sr.is_correct = true), 0)
       + COALESCE(COUNT(lqr.id) FILTER (WHERE lqr.is_correct = true), 0)) DESC
  ) AS position

FROM public.users u
LEFT JOIN public.student_responses sr        ON sr.user_id = u.id AND sr.instance = u.instance
LEFT JOIN public.local_question_responses lqr ON lqr.user_id = u.id AND lqr.instance = u.instance
WHERE u.role = 'ALUNO' AND u.active = true
GROUP BY u.id, u.instance, u.name, u.email, u.ra, u.curso, u.periodo, u.modalidade;

-- ---------------------------------------------------------------------------
-- 5.2  class_performance
-- ---------------------------------------------------------------------------
-- Per-class / per-course performance aggregation.

CREATE OR REPLACE VIEW public.class_performance AS
SELECT
  u.instance,
  u.curso,
  u.periodo,
  u.modalidade,
  COUNT(DISTINCT u.id) AS total_students,
  AVG(
    CASE WHEN (sr_count + lqr_count) > 0
      THEN ROUND(((sr_correct + lqr_correct)::FLOAT / (sr_count + lqr_count)::FLOAT) * 100)
      ELSE 0
    END
  ) AS avg_hit_rate
FROM public.users u
LEFT JOIN LATERAL (
  SELECT
    COUNT(sr.id)   AS sr_count,
    COUNT(sr.id) FILTER (WHERE sr.is_correct = true) AS sr_correct
  FROM public.student_responses sr
  WHERE sr.user_id = u.id AND sr.instance = u.instance
) sub_sr ON true
LEFT JOIN LATERAL (
  SELECT
    COUNT(lqr.id)  AS lqr_count,
    COUNT(lqr.id) FILTER (WHERE lqr.is_correct = true) AS lqr_correct
  FROM public.local_question_responses lqr
  WHERE lqr.user_id = u.id AND lqr.instance = u.instance
) sub_lqr ON true
WHERE u.role = 'ALUNO' AND u.active = true
GROUP BY u.instance, u.curso, u.periodo, u.modalidade;

-- ---------------------------------------------------------------------------
-- 5.3  microarea_performance
-- ---------------------------------------------------------------------------
-- Per-microarea hit-rate analytics (local bank responses only, since those
-- are the primary source of topic-level data).

CREATE OR REPLACE VIEW public.microarea_performance AS
SELECT
  lqr.instance,
  lqr.topic       AS microarea_name,
  lqr.macroarea,
  COUNT(lqr.id)   AS total_answered,
  COUNT(lqr.id) FILTER (WHERE lqr.is_correct = true) AS total_correct,
  CASE
    WHEN COUNT(lqr.id) > 0
    THEN ROUND((COUNT(lqr.id) FILTER (WHERE lqr.is_correct = true)::FLOAT / COUNT(lqr.id)::FLOAT) * 100)
    ELSE 0
  END AS hit_rate,
  ROUND(AVG(lqr.response_time)) AS avg_response_time
FROM public.local_question_responses lqr
GROUP BY lqr.instance, lqr.topic, lqr.macroarea;


